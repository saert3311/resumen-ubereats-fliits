export interface DaySummary {
  date: string;
  dayName: string;
  totalOrders: number;
  completedOrders: number;
  cancelledOrders: number;
  totalDistanceKm: number;
  totalSeconds: number;
  avgDurationMinutes: number;
  avgDurationSeconds: number;
}

export function calculateSummary(orders: OrderItem[] = UBER_ORDERS) {
  const totalOrders = orders.length;
  const completedOrders = orders.filter((o) => o.status === 'completed');
  const cancelledOrders = orders.filter((o) => o.status === 'cancelled');

  const totalDistanceKm = completedOrders.reduce((sum, o) => sum + o.distanceKm, 0);
  const totalSeconds = completedOrders.reduce(
    (sum, o) => sum + o.durationMinutes * 60 + o.durationSeconds,
    0
  );

  const avgSeconds = completedOrders.length > 0 ? totalSeconds / completedOrders.length : 0;
  const avgMin = Math.floor(avgSeconds / 60);
  const avgSecRem = Math.round(avgSeconds % 60);

  // Group by day
  const dayMap = new Map<string, OrderItem[]>();
  orders.forEach((o) => {
    if (!dayMap.has(o.date)) {
      dayMap.set(o.date, []);
    }
    dayMap.get(o.date)!.push(o);
  });

  const days: DaySummary[] = [];
  dayMap.forEach((dayOrders, date) => {
    const dayComp = dayOrders.filter((o) => o.status === 'completed');
    const dayDist = dayComp.reduce((s, o) => s + o.distanceKm, 0);
    const daySec = dayComp.reduce((s, o) => s + o.durationMinutes * 60 + o.durationSeconds, 0);
    const dayAvgSec = dayComp.length > 0 ? daySec / dayComp.length : 0;

    days.push({
      date,
      dayName: dayOrders[0].dayName,
      totalOrders: dayOrders.length,
      completedOrders: dayComp.length,
      cancelledOrders: dayOrders.length - dayComp.length,
      totalDistanceKm: Number(dayDist.toFixed(2)),
      totalSeconds: daySec,
      avgDurationMinutes: Math.floor(dayAvgSec / 60),
      avgDurationSeconds: Math.round(dayAvgSec % 60),
    });
  });

  // Group by brand
  const brandMap = new Map<string, { count: number; totalKm: number }>();
  orders.forEach((o) => {
    // Normalise brand name
    let brand = o.restaurant.split('(')[0].split('-')[0].trim();
    if (brand.toLowerCase().startsWith('dia')) brand = 'DIA';
    if (brand.toLowerCase().startsWith('kfc')) brand = 'KFC';
    if (brand.toLowerCase().startsWith("mcdonald's")) brand = "McDonald's";
    if (brand.toLowerCase().startsWith('burger king')) brand = 'Burger King';
    if (brand.toLowerCase().startsWith('city poké')) brand = 'City Poké';
    if (brand.toLowerCase().startsWith('oh tacoos')) brand = 'Oh Tacoos';

    const curr = brandMap.get(brand) || { count: 0, totalKm: 0 };
    curr.count += 1;
    curr.totalKm += o.distanceKm;
    brandMap.set(brand, curr);
  });

  const brands = Array.from(brandMap.entries())
    .map(([name, data]) => ({
      name,
      count: data.count,
      totalKm: Number(data.totalKm.toFixed(2)),
    }))
    .sort((a, b) => b.count - a.count);

  return {
    totalOrders,
    completedCount: completedOrders.length,
    cancelledCount: cancelledOrders.length,
    totalDistanceKm: Number(totalDistanceKm.toFixed(2)),
    totalHours: Math.floor(totalSeconds / 3600),
    totalMinutesRem: Math.floor((totalSeconds % 3600) / 60),
    totalSecondsRem: totalSeconds % 60,
    avgDurationMinutes: avgMin,
    avgDurationSeconds: avgSecRem,
    avgDurationDecimal: Number((avgSeconds / 60).toFixed(2)),
    days,
    brands,
  };
}

export function formatDuration(minutes: number, seconds: number): string {
  if (minutes === 0 && seconds === 0) return 'Cancelado';
  if (minutes >= 60) {
    const hours = Math.floor(minutes / 60);
    const remMin = minutes % 60;
    if (seconds > 0) {
      return `${hours} h ${remMin} min ${seconds} s`;
    }
    return `${hours} h ${remMin} min`;
  }
  return `${minutes} min ${seconds} seg`;
}
